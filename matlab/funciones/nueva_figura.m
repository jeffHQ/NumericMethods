function ax = nueva_figura(nombre, par, ancho)
    % Figura con el eje a la izquierda y, a la derecha, un recuadro con la
    % definicion de las variables (siempre visible, fuera de las curvas).
    if nargin < 3, ancho = 980; end
    fig = figure('Name', nombre, 'Position', [100, 100, ancho, 460], 'Color', 'w');
    try, theme(fig, 'light'); catch, end   % evita el tema oscuro (texto ilegible al exportar)
    ax = axes(fig, 'Position', [0.08 0.14 0.60 0.78]);
    hold(ax, 'on'); grid(ax, 'on'); box(ax, 'on');

    txt = { '\bfDefinición de variables', ...
            'T(x,t): temperatura (°C)', ...
            'x: posición (m);  t: tiempo (s)', ...
            texto_valor('v = %g m/s: velocidad del fluido', 'v: velocidad del fluido (m/s), varía', par.v), ...
            sprintf('\\alpha_0 = %g m^2/s: difusividad de ref.', par.alpha0), ...
            sprintf('\\beta = %g 1/°C: coef. de variación de \\alpha', par.beta), ...
            sprintf('T_0 = %g °C: temperatura de ref.', par.T0), ...
            sprintf('T_1 = %g °C: temperatura en x = 0', par.T1), ...
            sprintf('T_N = %g °C: temperatura en x = L', par.TN), ...
            sprintf('L = %g m;  \\Deltax = %g m;  h = %g s', par.L, par.dx, par.h) };
    annotation(fig, 'textbox', [0.70 0.50 0.29 0.42], 'String', txt, ...
        'Interpreter', 'tex', 'FontSize', 9, 'BackgroundColor', [0.96 0.96 0.96], ...
        'EdgeColor', [0.4 0.4 0.4], 'FitBoxToText', 'off', 'VerticalAlignment', 'top');
end

function t = texto_valor(fmt, fmt_var, valor)
    % Si el parametro es NaN (barrido), se indica que varia en vez de mostrar un valor.
    if isnan(valor), t = fmt_var; else, t = sprintf(fmt, valor); end
end
